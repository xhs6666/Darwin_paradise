"""Compile current asmdef source sets using installed Unity references, without changing generated projects."""
from pathlib import Path
import xml.etree.ElementTree as ET
import sys
root=Path(__file__).resolve().parents[1]
output=root/'Artifacts/ServerCompile';output.mkdir(parents=True,exist_ok=True)
mode=sys.argv[1] if len(sys.argv)>1 else 'editor'
asmdefs={p.parent:__import__('json').loads(p.read_text(encoding='utf-8-sig')) for p in (root/'Assets').rglob('*.asmdef')}
sources={a['name']:[] for a in asmdefs.values()};sources['Assembly-CSharp']=[]
for p in (root/'Assets').rglob('*.cs'):
    owners=[d for d in asmdefs if p.is_relative_to(d)]
    name=asmdefs[max(owners,key=lambda x:len(x.parts))]['name'] if owners else 'Assembly-CSharp'
    sources[name].append(p)
for name,files in sources.items():
    original=root/(name+'.csproj')
    old=ET.parse(original).getroot() if original.exists() else None
    if old is None and name!='DarwinPark.ServerCore':old=ET.parse(root/'DarwinPark.UI.csproj').getroot()
    project=ET.Element('Project',Sdk='Microsoft.NET.Sdk');props=ET.SubElement(project,'PropertyGroup')
    # Unity 引用集只做托管源码编译，无需探测机器级 Windows SDK 或用户 SDK 缓存。
    values={'TargetFramework':'netstandard2.1','LangVersion':'9.0','EnableDefaultItems':'false','GenerateAssemblyInfo':'false','NoWarn':'0169;0649;USG0001','AssemblyName':name,'UseSharedCompilation':'false','_EnableDefaultWindowsPlatform':'false'}
    if old is not None:
        defines=old.findtext('.//DefineConstants') or ''
        if mode in ['server','client'] and name!='DarwinPark.Editor':defines=';'.join(x for x in defines.split(';') if x not in ['UNITY_EDITOR','UNITY_EDITOR_WIN','UNITY_EDITOR_64'])+(';UNITY_SERVER' if mode=='server' else '')
        values['DefineConstants']=defines
    elif mode=='server':values['DefineConstants']='UNITY_SERVER'
    for key,value in values.items():ET.SubElement(props,key).text=value
    items=ET.SubElement(project,'ItemGroup')
    for p in files:ET.SubElement(items,'Compile',Include=str(p))
    if old is not None:
        for reference in old.findall('.//Reference'):
            if reference.attrib['Include'] in ['mscorlib','netstandard'] or reference.attrib['Include'].startswith(('System','Mono.','Microsoft.CSharp')):continue
            hint=reference.findtext('HintPath')
            if not hint:continue
            path=Path(hint);path=path if path.is_absolute() else root/path
            item=ET.SubElement(items,'Reference',Include=reference.attrib['Include']);ET.SubElement(item,'HintPath').text=str(path)
    info=next((a for a in asmdefs.values() if a['name']==name),None)
    dependencies=info.get('references',[]) if info else [n for n in sources if n not in ['Assembly-CSharp','DarwinPark.Editor']]
    for dep in dependencies:ET.SubElement(items,'ProjectReference',Include='../'+dep+'/'+dep+'.csproj')
    destination=output/name;destination.mkdir(parents=True,exist_ok=True)
    ET.indent(project);ET.ElementTree(project).write(destination/(name+'.csproj'),encoding='utf-8',xml_declaration=True)
    if '--sync-projects' in sys.argv:
        # Rebuild only autogenerated IDE source/reference lists, retaining Unity's framework reference set for FlowDocs.
        ide=ET.fromstring(ET.tostring(old)) if old is not None and name!='DarwinPark.ServerCore' else ET.parse(root/'DarwinPark.UI.csproj').getroot()
        for group in ide.findall('ItemGroup'):
            for item in list(group):
                if item.tag in ['Compile','ProjectReference']:group.remove(item)
                elif name=='DarwinPark.ServerCore' and item.tag=='Reference' and not any(part in (item.findtext('HintPath') or '').lower() for part in ['unityreferenceassemblies','netstandard']):group.remove(item)
        for prop in ['AssemblyName','RootNamespace']:
            for element in ide.findall('.//'+prop):element.text=name
        group=ET.SubElement(ide,'ItemGroup')
        for p in files:ET.SubElement(group,'Compile',Include=p.relative_to(root).as_posix())
        for dep in dependencies:ET.SubElement(group,'ProjectReference',Include=dep+'.csproj')
        ET.indent(ide);ET.ElementTree(ide).write(root/(name+'.csproj'),encoding='utf-8',xml_declaration=True)
print(output)
